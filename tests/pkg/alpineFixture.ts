// Building Alpine .apk packages (the gzip-based v2 format) as exact bytes.
//
// Written from apk-tools' package format description: the file is two or three
// gzip streams concatenated. An optional signature stream holds one tar file
// named `.SIGN.RSA.<key>`; the control stream holds `.PKGINFO` and optional
// scripts; the data stream holds the files. The signature and control tars are
// segments: they end without the two zero blocks, so the streams read as one tar.
import { gzipSync } from 'fflate';
import { concat, paxRecord, tar, type TarSpec } from './debFixture';

export const KEY_NAME = 'alpine-devel@lists.alpinelinux.org-6165ee59.rsa.pub';
export const DATAHASH = 'ab'.repeat(32);

export const PKGINFO = [
  '# Generated by abuild 3.12.0',
  '# using fakeroot version 1.32.1',
  'pkgname = curl',
  'pkgver = 8.5.0-r0',
  'pkgdesc = URL retrieval utility and library',
  'url = https://curl.se/',
  'builddate = 1700000000',
  'packager = Buildozer <alpine-devel@lists.alpinelinux.org>',
  'size = 262144',
  'arch = x86_64',
  'origin = curl',
  'commit = 0123456789abcdef0123456789abcdef01234567',
  'maintainer = Ana Example <ana@example.org>',
  'license = MIT',
  'depend = ca-certificates',
  'depend = so:libc.musl-x86_64.so.1',
  'depend = !curl-old',
  'depend = zlib>=1.2',
  'replaces = curl-legacy',
  'provides = cmd:curl=8.5.0-r0',
  'provides = so:libcurl.so.4=4.8.0',
  'install_if = docs=8.5.0-r0',
  'triggers = /usr/share/ca-certificates /etc/ssl/certs',
  `datahash = ${DATAHASH}`,
  '',
].join('\n');

export interface ApkSpec {
  pkginfo?: string;
  /** Names of control scripts, such as ".post-install". */
  scripts?: string[];
  /** The key name after `.SIGN.RSA.`; null leaves the signature stream out. */
  signature?: string | null;
  /** Write the signature's name in a pax header, as abuild does. */
  pax?: boolean;
  /** The data stream, replacing the built one. */
  data?: Uint8Array;
}

const gz = (bytes: Uint8Array): Uint8Array => gzipSync(bytes);

export function buildApk(spec: ApkSpec = {}): Uint8Array {
  const parts: Uint8Array[] = [];
  const signature = spec.signature === undefined ? KEY_NAME : spec.signature;
  if (signature !== null) {
    const name = `.SIGN.RSA.${signature}`;
    const entries: TarSpec[] = spec.pax
      ? [
          { name: `./PaxHeaders/${name}`, type: 'x', data: paxRecord('path', name) },
          { name: 'placeholder', data: 'signature bytes' },
        ]
      : [{ name, data: 'signature bytes' }];
    parts.push(gz(tar(entries, false)));
  }
  const control: TarSpec[] = [{ name: '.PKGINFO', data: spec.pkginfo ?? PKGINFO }];
  for (const script of spec.scripts ?? []) {
    control.push({ name: script, data: '#!/bin/sh\nexit 0\n' });
  }
  parts.push(gz(tar(control, false)));
  parts.push(
    spec.data ??
      gz(
        tar([
          { name: 'usr/', type: '5' },
          { name: 'usr/bin/curl', data: new Uint8Array(3000).fill(1) },
        ]),
      ),
  );
  return concat(...parts);
}
